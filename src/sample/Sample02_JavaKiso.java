package sample;

public class Sample02_JavaKiso {

	public static void main(String[] args) {
		int x; 					// 変数宣言
		x = 10; 				// 代入
		int y = 20; 			// 変数宣言と代入を同時
		int z = x + y; 			// 加算
		int v = 40;
		v++; 					// カウントアップ
		System.out.println(x); 	// 表示して改行
		System.out.print(y); 	// 表示のみ
		System.out.println(z); 	// 表示して改行
		System.out.println(v); 	// 表示して改行
	}

}
